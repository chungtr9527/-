// Rewrites www/js/build-flags.js (and the test ad-id script tag) for a dev or release build. Idempotent.
//   node scripts/apply-build-flags.js dev      -> env 'test', debugHooks true, test ad ids present
//   node scripts/apply-build-flags.js release  -> env 'prod', debugHooks false, test ad ids removed
'use strict';
const fs = require('fs');
const path = require('path');
const mode = process.argv[2];
if (mode !== 'dev' && mode !== 'release') { console.error('usage: apply-build-flags.js dev|release'); process.exit(2); }
const www = path.join(__dirname, '..', 'www');
const flagsFile = path.join(www, 'js', 'build-flags.js');
const indexFile = path.join(www, 'index.html');
const testIdsFile = path.join(www, 'js', 'ads-ids.test.js');
const flags = mode === 'dev' ? { env: 'test', debugHooks: true } : { env: 'prod', debugHooks: false };
fs.writeFileSync(flagsFile, `// Generated by scripts/apply-build-flags.js (${mode}). Do not edit by hand.\n` +
  `(function (g) { var TB = g.TB || (g.TB = {}); TB.flags = ${JSON.stringify(flags)}; })(typeof globalThis !== 'undefined' ? globalThis : window);\n`);
let html = fs.readFileSync(indexFile, 'utf8');
const tag = '<script src="js/ads-ids.test.js"></script>';
const marker = '<!-- ads-ids.test.js (removed in release builds) -->';
if (mode === 'release') {
  html = html.replace(tag, marker);
  if (fs.existsSync(testIdsFile)) fs.unlinkSync(testIdsFile);
} else {
  html = html.replace(marker, tag);
  if (!fs.existsSync(testIdsFile)) {
    fs.writeFileSync(testIdsFile, fs.readFileSync(path.join(__dirname, 'ads-ids.test.template.js'), 'utf8'));
  }
}
fs.writeFileSync(indexFile, html);
console.log(`build flags: ${JSON.stringify(flags)}; ${mode === 'release' ? 'test ad ids removed' : 'test ad ids present'}`);
